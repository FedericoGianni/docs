#!/usr/bin/env bash
#
# merge_docs.sh - Merge all Markdown docs into a single file.
#
# Dynamically discovers every *.md file inside the docs directory, orders
# them by their numeric index (index.md first, then 1-, 2-, 3-, ...),
# and concatenates the contents into one Markdown document.
#
# Usage:
#   scripts/merge_docs.sh [OUTPUT_FILE]
#
# Arguments:
#   OUTPUT_FILE   Destination file (default: <repo>/docs/ALL.md)
#
# Environment:
#   DOCS_DIR   Directory to scan for *.md files (default: <repo>/docs)
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

DOCS_DIR="${DOCS_DIR:-${REPO_ROOT}/docs}"
OUTPUT_FILE="${1:-${DOCS_DIR}/ALL.md}"

if [[ ! -d "${DOCS_DIR}" ]]; then
    echo "error: DOCS_DIR does not exist: ${DOCS_DIR}" >&2
    exit 1
fi

# Collect all *.md files, excluding the output file itself and the
# canonical merge output (ALL.md), so the script stays idempotent even
# when a custom OUTPUT_FILE is used.
mapfile -t FILES < <(
    find "${DOCS_DIR}" -maxdepth 1 -type f -name '*.md' \
        ! -name "$(basename "${OUTPUT_FILE}")" \
        ! -name 'ALL.md' | sort
)

if [[ ${#FILES[@]} -eq 0 ]]; then
    echo "error: no *.md files found in ${DOCS_DIR}" >&2
    exit 1
fi

# Order by numeric index: index.md first, then 1-, 2-, 3-, ... and finally
# any file without a numeric prefix (kept in their original sorted order).
# Uses sort with a zero-padded numeric key so 10- sorts after 9-.
ORDERED=$(
    for f in "${FILES[@]}"; do
        base="$(basename "${f}")"
        if [[ "${base}" == "index.md" ]]; then
            key="000"
        elif [[ "${base}" =~ ^([0-9]+)- ]]; then
            key="$(printf '%03d' "${BASH_REMATCH[1]}")"
        else
            key="999"
        fi
        printf '%s\t%s\n' "${key}" "${f}"
    done | sort -t $'\t' -k1,1 -k2,2 | cut -f2-
)

if [[ -z "${ORDERED}" ]]; then
    echo "error: could not order markdown files" >&2
    exit 1
fi

{
    echo "# Forbay Homelab Docs"
    echo
    echo "> Generated by \`scripts/merge_docs.sh\` — merge of the following pages:"
    echo
    while IFS= read -r f; do
        echo "- [$(basename "${f}")]"
    done <<< "${ORDERED}"
    echo
    echo "---"
    echo

    while IFS= read -r f; do
        cat "${f}"
        echo
        echo "---"
        echo
    done <<< "${ORDERED}"
} > "${OUTPUT_FILE}"

echo "Merged ${#FILES[@]} files into: ${OUTPUT_FILE}"
